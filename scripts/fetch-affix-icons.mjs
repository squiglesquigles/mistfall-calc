/**
 * fetch-affix-icons.mjs — download the affix icons from mistfalldb.com into
 * frontend/src/assets/icons/affixes/ and generate frontend/src/lib/affixIcons.js
 * (a name -> bundled-image lookup the UI imports).
 *
 * Uses the saved page (affixes_raw.html) for the icon URLs, then downloads once.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { load } from 'cheerio';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const BASE = 'https://mistfalldb.com';
const HTML = path.join(ROOT, 'affixes_raw.html');
const AFFIXES = path.join(ROOT, 'backend', 'data', 'affixes.json');
const OUT_DIR = path.join(ROOT, 'frontend', 'src', 'assets', 'icons', 'affixes');
const MODULE = path.join(ROOT, 'frontend', 'src', 'lib', 'affixIcons.js');

const affixes = JSON.parse(readFileSync(AFFIXES, 'utf8'));
const names = new Set(affixes.map(a => a.name));

// name -> icon url from the saved page
const $ = load(readFileSync(HTML, 'utf8'));
const iconByAlt = {};
$('img').each((_, node) => {
  const alt = $(node).attr('alt') || '';
  const src = $(node).attr('src') || '';
  const m = alt.match(/^(.*?)\s*icon$/i);
  if (m && src) iconByAlt[m[1].trim()] = src.startsWith('http') ? src : (BASE + src);
});

mkdirSync(OUT_DIR, { recursive: true });
const ok = [];
const failed = [];
for (const a of affixes) {
  const url = iconByAlt[a.name] || (a.icon ? (a.icon.startsWith('http') ? a.icon : BASE + a.icon) : null);
  if (!url) { failed.push(a.name + ' (no icon url)'); continue; }
  const safe = a.name.replace(/[^A-Za-z0-9]+/g, '_') + '.webp';
  try {
    let buf;
    if (url.startsWith('http')) {
      const res = await fetch(url);
      if (!res.ok) throw new Error('HTTP ' + res.status);
      buf = Buffer.from(await res.arrayBuffer());
    } else {
      buf = readFileSync(path.join(ROOT, url.replace(/^\//, '')));
    }
    if (!buf.length) throw new Error('empty');
    writeFileSync(path.join(OUT_DIR, safe), buf);
    ok.push({ name: a.name, file: safe });
  } catch (e) {
    failed.push(a.name + ' (' + e.message + ')');
  }
}

// generate the lookup module
const lines = ['// AUTO-GENERATED by scripts/fetch-affix-icons.mjs — do not edit by hand.'];
for (const r of ok) {
  lines.push(`import ${'A' + r.name.replace(/\W/g, '')} from '../assets/icons/affixes/${r.file}';`);
}
lines.push('export const AFFIX_ICONS = {');
for (const r of ok) lines.push(`  '${r.name}': ${'A' + r.name.replace(/\W/g, '')},`);
lines.push('};');
writeFileSync(MODULE, lines.join('\n') + '\n', 'utf8');

console.log('Downloaded:', ok.length, '/', affixes.length);
if (failed.length) console.log('Failed/skipped:', failed.join(' | '));
console.log('Module written:', path.relative(ROOT, MODULE));