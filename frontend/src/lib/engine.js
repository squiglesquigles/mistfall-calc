/**
 * Mistfall Hunter Build Optimizer — browser (static) port of backend/optimizer.js
 * and backend/pricing.js.
 *
 * The original ran as a Node/Express service reading JSON from disk and exposing a
 * REST API. For free static hosting (GitHub/Cloudflare Pages) we run the exact same
 * MILP engine directly in the browser: the JSON data is bundled at build time and the
 * price index is built once in memory. Exports mirror the old /api/* responses so the
 * React UI calls these functions directly instead of fetch().
 */

import solver from 'javascript-lp-solver';
import { decodePack } from './codec';
import { DATA_ENC } from './data.enc.js';

// Decode the obfuscated data blob at runtime. The plain JSON in backend/data/
// is the source of truth; data.enc.js is generated by scripts/encode-data.mjs.
const P = decodePack(DATA_ENC);

const DATA = {
  classes: P.classes,
  gear: P.gear,
  gemCatalog: P.gem_catalog,
  affixes: P.affixes,
  affixRegistry: P.affix_registry
};
const PRICES = P.prices;
const ARMOR = P.armor;
const GEMS = P.gems;

function loadData() { return DATA; }

function validAffixSet() {
  const { affixes, affixRegistry } = DATA;
  const set = new Set();
  for (const a of affixes) if (a.name) set.add(a.name);
  for (const a of affixRegistry) if (a.name) set.add(a.name);
  return set;
}

// ---- Pricing (port of backend/pricing.js) ----
const DEFAULT_ARMOR_COST = 500;
const DEFAULT_WEAPON_COST = 1500;
const DEFAULT_GEM_COST = 150;

const WEAPON_SLOTS = new Set(['Weapon', 'Mace', 'Catalyst', 'Greatsword', 'Bow', 'Staff', 'Dagger', 'Dual Blades', 'Hammer', 'Sword and Shield', 'Polearm and Shield']);

function buildPriceIndex() {
  const priceByName = {};
  for (const p of PRICES) {
    if (p && p.name && p.price != null) priceByName[p.name] = Number(p.price);
  }
  for (const a of ARMOR) {
    if (a && a.name && a.recommendedPrice != null && priceByName[a.name] == null) {
      priceByName[a.name] = Number(a.recommendedPrice);
    }
  }
  const gemPriceByAffix = {};
  for (const g of GEMS) {
    if (g == null || g.gemLevel == null || !Array.isArray(g.affixes)) continue;
    const names = g.affixes.map(a => (a && a.name) || '').filter(Boolean).sort();
    const key = g.gemLevel + '|' + names.join('|');
    let price = DEFAULT_GEM_COST;
    if (g.recommendedPrice != null) price = Number(g.recommendedPrice);
    else if (g.minPrice != null && g.maxPrice != null) price = Math.round((Number(g.minPrice) + Number(g.maxPrice)) / 2);
    gemPriceByAffix[key] = price;
  }
  return { priceByName, armorPrice: priceByName, gemPriceByAffix, config: { DEFAULT_ARMOR_COST, DEFAULT_WEAPON_COST, DEFAULT_GEM_COST } };
}

function gearCost(index, gearName, slot) {
  if (index.priceByName[gearName] != null) return index.priceByName[gearName];
  return WEAPON_SLOTS.has(slot) ? DEFAULT_WEAPON_COST : DEFAULT_ARMOR_COST;
}

function gemCost(index, tier, affix1, affix2) {
  const names = [affix1, affix2].filter(Boolean).sort();
  const key = tier + '|' + names.join('|');
  const p = index.gemPriceByAffix[key];
  return p != null ? p : DEFAULT_GEM_COST;
}

